"""Write requirements.hashes.txt: every pin in requirements.lock.txt with the sha256 of each file PyPI publishes
for that exact version.

The image installs from this file with `pip install --require-hashes`, so a dependency that was swapped or tampered
with on the index (or on the way from it) fails the build instead of landing in the image. Run it after regenerating
requirements.lock.txt:

    python scripts/lock_hashes.py            # rewrite requirements.hashes.txt
    python scripts/lock_hashes.py --check    # exit 1 if it is out of date (CI)
"""
from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / 'requirements.lock.txt'
OUT = ROOT / 'requirements.hashes.txt'
SKIP = {'pip', 'setuptools', 'wheel'}  # the installer itself is bootstrapped separately in the Dockerfile


def pins() -> list[tuple[str, str, str]]:
    """(name, version, environment marker) for every pin in the lock."""
    out = []
    for line in LOCK.read_text().splitlines():
        line = line.split('#', 1)[0].strip()
        if '==' in line:
            requirement, _, marker = line.partition(';')
            name, version = requirement.split('==', 1)
            if name.strip().lower() not in SKIP:
                out.append((name.strip(), version.strip(), marker.strip()))
    return out


def hashes(name: str, version: str) -> list[str]:
    url = f'https://pypi.org/pypi/{name}/{version}/json'
    with urllib.request.urlopen(url, timeout=30) as resp:  # noqa: S310 - fixed https PyPI endpoint
        files = json.load(resp)['urls']
    found = sorted({f['digests']['sha256'] for f in files if not f.get('yanked')})
    if not found:
        raise SystemExit(f'no published files for {name}=={version}')
    return found


def render() -> str:
    lines = ['# Generated by scripts/lock_hashes.py from requirements.lock.txt. Do not edit by hand.',
             '# Installed in the image with: pip install --require-hashes --no-deps -r requirements.hashes.txt']
    for name, version, marker in pins():
        digests = hashes(name, version)
        lines.append(f'{name}=={version}' + (f' ; {marker}' if marker else '') + ' \\')
        lines.extend(f'    --hash=sha256:{d}' + (' \\' if i < len(digests) - 1 else '') for i, d in enumerate(digests))
    return '\n'.join(lines) + '\n'


def main() -> int:
    text = render()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print('requirements.hashes.txt is out of date; run: python scripts/lock_hashes.py', file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f'wrote {OUT.name}: {len(pins())} packages')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
